// CrossMosa v185 — the DEFAULT bank: same vendor drives, re-pointed to the plane
// combos CrossPoint actually produces. CrossPoint's planes (GfxRenderer
// GRAYSCALE_LSB/MSB, planes cleared to 0, marked pixel = 1, LSB -> DTM1/old,
// MSB -> DTM2/new) put DARK gray at (1,1) = WW and LIGHT gray at (0,1) = BW;
// black text / white background sit at (0,0) = BB; (1,0) = WB never occurs
